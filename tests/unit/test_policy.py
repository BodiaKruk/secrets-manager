@pytest.fixture()
def doc():
    return PolicyTranslator.load_yaml(SAMPLE_YAML)


@pytest.mark.unit
class TestLoadAndValidate:
    def test_load_yaml_returns_dict(self, doc):
        assert isinstance(doc, dict)

    def test_version_parsed(self, doc):
        assert doc["version"] == "1.0"

    def test_rule_count(self, doc):
        assert len(doc["rules"]) == 3

    def test_validate_passes_on_valid(self, doc):
        PolicyTranslator.validate_yaml(doc)  # should not raise

    def test_validate_missing_rules_raises(self):
        with pytest.raises(ValueError, match="rules"):
            PolicyTranslator.validate_yaml({"version": "1.0"})

    def test_validate_empty_rules_raises(self):
        with pytest.raises(ValueError, match="non-empty"):
            PolicyTranslator.validate_yaml({"rules": []})

    def test_validate_missing_path_raises(self):
        with pytest.raises(ValueError, match="path"):
            PolicyTranslator.validate_yaml({"rules": [{"capabilities": ["read"], "principals": []}]})

    def test_validate_unknown_cap_raises(self):
        with pytest.raises(ValueError, match="unknown values"):
            PolicyTranslator.validate_yaml({
                "rules": [{"path": "x", "capabilities": ["teleport"], "principals": []}]
            })

    def test_validate_bad_principal_type_raises(self):
        with pytest.raises(ValueError, match="unknown"):
            PolicyTranslator.validate_yaml({
                "rules": [{
                    "path": "x",
                    "capabilities": ["read"],
                    "principals": [{"type": "ghost", "id": "x"}],
                }]
            })


